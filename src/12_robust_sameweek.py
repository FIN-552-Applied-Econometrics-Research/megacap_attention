"""
Card 16: robustness - same-week twins only.

In 05_match.py, a treated announcement with no same-industry candidate in its
own event window (2-5 trading days from ITS mega-cap day) got a twin from the
same calendar quarter instead (match_level = 2). Clustered mega-cap weeks
(Meta, Microsoft, Alphabet) needed that fallback most.

This script keeps only treated-twin pairs matched within the same event week
(match_level = 1) and re-runs the task 11/12 regressions with exactly the same
controls, fixed effects, units and clustering (it imports src/08_regress.py).

Outputs: output/tables/robust_sameweek.tex   beta_3 baseline vs same-week, both
                                             outcomes, base and + market move;
                                             plus the sample cost by mega-cap
         output/robust_sameweek.md
Usage  : python src/12_robust_sameweek.py
"""

import importlib.util
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
TEX = REPO_ROOT / "output" / "tables" / "robust_sameweek.tex"
MD = REPO_ROOT / "output" / "robust_sameweek.md"
MEGAS = ["NVDA", "AAPL", "MSFT", "GOOGL", "AMZN", "META"]


def load_regress():
    spec = importlib.util.spec_from_file_location("regress", REPO_ROOT / "src" / "08_regress.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def main():
    rg = load_regress()
    s = rg.load()                                      # 1:1 sample, task 12 variables

    # same-week pairs: the treated row's match_level is 1; keep it and its twin
    same_ids = s.loc[(s["role"] == "treated") & (s["match_level"] == 1), "match_id"]
    sw = s[s["match_id"].isin(same_ids)]

    # ---- sample cost by mega-cap ----
    t_all = s[s["role"] == "treated"]
    t_sw = sw[sw["role"] == "treated"]
    cost = []
    for tk in MEGAS:
        a = t_all["nearest_mega"].str.contains(tk).sum()
        k = t_sw["nearest_mega"].str.contains(tk).sum()
        cost.append((tk, a, k, k / a if a else float("nan")))
    cost.append(("All", len(t_all), len(t_sw), len(t_sw) / len(t_all)))
    events_all, events_sw = t_all["event_id"].nunique(), t_sw["event_id"].nunique()

    # ---- regressions: baseline vs same-week, both outcomes, both specs ----
    res = {}
    for y in ("car01", "car2_60"):
        for mkt in (False, True):
            for name, df in (("base", s), ("same", sw)):
                m, d = rg.fit(df, y, mkt)
                lo, hi = m.conf_int().loc["sue:megaday"]
                res[(y, mkt, name)] = {"b": m.params["sue:megaday"], "t": m.tvalues["sue:megaday"],
                                       "p": m.pvalues["sue:megaday"], "lo": lo, "hi": hi,
                                       "b1": m.params["sue"], "n": int(m.nobs),
                                       "cl": d["reaction_day"].nunique()}
                r = res[(y, mkt, name)]
                print(f"{y:8} {'+mkt' if mkt else 'base':5} {name:5} b3 = {r['b']:+.3f} "
                      f"(t = {r['t']:+.2f}) CI [{r['lo']:.2f}, {r['hi']:.2f}]  N = {r['n']:,}")

    # ------------------------------ LaTeX ------------------------------
    num, stars = rg.num, rg.stars
    cols = [(y, n) for y in ("car01", "car2_60") for n in ("base", "same")]
    L = [r"% Generated by src/12_robust_sameweek.py. Requires \usepackage{booktabs}.",
         r"\begin{table}[htbp]", r"\centering", r"\small",
         r"\caption{Robustness: twins from the same event week only}",
         r"\label{tab:robust_sameweek}", r"\begin{tabular}{lcccc}", r"\toprule",
         r" & \multicolumn{2}{c}{CAR$(0,+1)$} & \multicolumn{2}{c}{CAR$(+2,+60)$} \\",
         r"\cmidrule(lr){2-3} \cmidrule(lr){4-5}",
         r" & All twins & Same week & All twins & Same week \\",
         r" & (1) & (2) & (3) & (4) \\", r"\midrule"]
    for mkt, title in ((False, "Panel A: Base"), (True, "Panel B: With market-move control")):
        L.append(rf"\multicolumn{{5}}{{l}}{{\emph{{{title}}}}} \\")
        L.append(r"SUE $\times$ MegaDay ($\beta_3$) & " + " & ".join(
            f"${num(res[(y, mkt, n)]['b'])}{stars(res[(y, mkt, n)]['p'])}$" for y, n in cols) + r" \\")
        L.append(" & " + " & ".join(f"$({num(res[(y, mkt, n)]['t'], 2)})$" for y, n in cols) + r" \\")
        L.append(r"95\% CI & " + " & ".join(
            f"$[{num(res[(y, mkt, n)]['lo'], 2)}, {num(res[(y, mkt, n)]['hi'], 2)}]$" for y, n in cols) + r" \\")
        L.append(r"SUE ($\beta_1$) & " + " & ".join(
            f"${num(res[(y, mkt, n)]['b1'])}$" for y, n in cols) + r" \\")
        L.append(r"Observations & " + " & ".join(f"{res[(y, mkt, n)]['n']:,}" for y, n in cols) + r" \\[2pt]")
        if not mkt:
            L.append(r"\midrule")
    L += [r"\bottomrule", r"\end{tabular}", r"\par\medskip",
          r"\begin{tabular}{lrrr}", r"\toprule",
          r"Mega-cap & Treated (all) & Same-week twin & Kept \\", r"\midrule"]
    for tk, a, k, sh in cost:
        if tk == "All":
            L.append(r"\midrule")
        L.append(f"{tk} & {a:,} & {k:,} & {100 * sh:.0f}\\% \\\\")
    L += [rf"Events & {events_all} & {events_sw} & \\",
          r"\bottomrule", r"\end{tabular}", r"\par\medskip",
          r"\parbox{0.95\linewidth}{\footnotesize Columns (1) and (3) repeat Table~\ref{tab:main} "
          r"on the full 1:1 matched sample. Columns (2) and (4) keep only treated announcements whose "
          r"twin reported 2 to 5 trading days from the treated firm's own mega-cap reaction day, in the "
          r"same FF12 industry (no same-quarter fallback). Same controls, industry and quarter fixed "
          r"effects, units and clustering by reaction day as Table~\ref{tab:main}. The lower panel "
          r"counts treated announcements by mega-cap (a day shared by two mega-caps counts under both). "
          r"$t$-statistics in parentheses; $^{*}$, $^{**}$, $^{***}$: 10\%, 5\%, 1\%.}",
          r"\end{table}"]
    TEX.parent.mkdir(parents=True, exist_ok=True)
    TEX.write_text("\n".join(L) + "\n", encoding="utf-8")

    # ------------------------------ Markdown ------------------------------
    M = ["## Robustness: same-week twins only", "",
         "| Spec | Outcome | All twins: beta_3 (t) [95% CI] N | Same week: beta_3 (t) [95% CI] N |",
         "|---|---|---|---|"]
    for mkt in (False, True):
        for y in ("car01", "car2_60"):
            a, b = res[(y, mkt, "base")], res[(y, mkt, "same")]
            M.append(f"| {'+ market move' if mkt else 'base'} | {y} | {a['b']:.3f} ({a['t']:.2f}) "
                     f"[{a['lo']:.2f}, {a['hi']:.2f}] {a['n']:,} | {b['b']:.3f} ({b['t']:.2f}) "
                     f"[{b['lo']:.2f}, {b['hi']:.2f}] {b['n']:,} |")
    M += ["", "| Mega-cap | Treated (all) | Same-week twin | Kept |", "|---|---|---|---|"]
    M += [f"| {tk} | {a:,} | {k:,} | {100 * sh:.0f}% |" for tk, a, k, sh in cost]
    M.append(f"| Events | {events_all} | {events_sw} | |")
    MD.write_text("\n".join(M) + "\n", encoding="utf-8")
    print("\n" + "\n".join(M))
    print(f"\nSaved {TEX.relative_to(REPO_ROOT)} and {MD.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
